-- 로그인 아이디를 킹고아이디에서 떼어낸다.
--
-- kingo_id 는 학교 포털 아이디, 사무처가 명단에 적어 넣는 참고값이다. 그런데
-- 첫 로그인이 회원이 고른 아이디를 같은 칸에 덮어써 왔다. 한 칸이 두 뜻을
-- 가지니 "아이디를 직접 만든 회원"과 "사무처가 킹고아이디만 적어둔 회원"이
-- 구분되지 않았고, 엑셀에 킹고아이디를 채워 올리면 회원이 아이디를 고를
-- 기회를 잃었다.
--
-- 로그인 아이디는 회원 본인만 만든다. 그래서 기존 kingo_id 값은 옮기지 않고
-- 빈 칸으로 시작한다. login_id 가 비어 있으면 아직 계정을 등록하지 않은
-- 회원이고, 관리자 화면은 이들을 '계정 미등록'으로 따로 모아 보여준다.
--
-- 옮기지 않는 대신, 이미 첫 로그인을 마친 회원은 자기 아이디로 로그인할 수
-- 없게 된다. 학번과 이메일로는 그대로 로그인되고, 아이디는 앱의 '계정 만들기'
-- 에서 다시 정하면 된다 — 활성 회원도 아이디가 비어 있으면 만들 수 있다.

ALTER TABLE users ADD COLUMN login_id VARCHAR(255) NULL;

-- 아이디는 회원끼리 겹칠 수 없다. 비워둔 칸(NULL)은 여럿이어도 된다.
ALTER TABLE users ADD CONSTRAINT uk_users_login_id UNIQUE (login_id);
